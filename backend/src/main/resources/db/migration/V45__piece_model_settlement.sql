CREATE TABLE piece_model_settlement (
    id BIGINT NOT NULL AUTO_INCREMENT,
    piece_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    structure_complexity VARCHAR(64) NULL,
    texture_level VARCHAR(32) NULL,
    simple_component_count INT NOT NULL DEFAULT 0,
    regular_curve_component_count INT NOT NULL DEFAULT 0,
    irregular_curve_component_count INT NOT NULL DEFAULT 0,
    high_detail_component_count INT NOT NULL DEFAULT 0,
    simple_inlay_count INT NOT NULL DEFAULT 0,
    special_inlay_count INT NOT NULL DEFAULT 0,
    linear_stone_count INT NOT NULL DEFAULT 0,
    freeform_stone_count INT NOT NULL DEFAULT 0,
    coefficient INT NOT NULL DEFAULT 10,
    note VARCHAR(500) NULL,
    reviewer_id BIGINT NULL,
    reviewed_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_piece_model_settlement_piece (piece_id),
    KEY idx_piece_model_settlement_order (order_id)
);
